CREATE TABLE monitor.monitors (
    id uuid PRIMARY KEY,
    name varchar(100) NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 100),
    url varchar(2048) NOT NULL,
    interval_seconds integer NOT NULL CHECK (interval_seconds BETWEEN 10 AND 3600),
    timeout_seconds integer NOT NULL CHECK (timeout_seconds BETWEEN 1 AND 30 AND timeout_seconds < interval_seconds),
    expected_status integer NOT NULL CHECK (expected_status BETWEEN 200 AND 599),
    failure_threshold integer NOT NULL CHECK (failure_threshold BETWEEN 1 AND 10),
    recovery_threshold integer NOT NULL CHECK (recovery_threshold BETWEEN 1 AND 10),
    alert_recipient varchar(254) NOT NULL,
    lifecycle varchar(6) NOT NULL CHECK (lifecycle IN ('ACTIVE', 'PAUSED')),
    confirmed_state varchar(7) NOT NULL CHECK (confirmed_state IN ('UNKNOWN', 'UP', 'DOWN')),
    failure_count integer NOT NULL CHECK (failure_count BETWEEN 0 AND 10),
    recovery_count integer NOT NULL CHECK (recovery_count BETWEEN 0 AND 10),
    first_failure_at timestamptz,
    recovery_started_at timestamptz,
    last_observed_at timestamptz,
    current_observation boolean NOT NULL,
    open_incident_id uuid,
    configuration_version bigint NOT NULL CHECK (configuration_version >= 1),
    execution_generation bigint NOT NULL CHECK (execution_generation >= 1),
    next_check_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CHECK (open_incident_id IS NULL OR confirmed_state = 'DOWN'),
    CHECK (NOT current_observation OR last_observed_at IS NOT NULL),
    CHECK (lifecycle <> 'PAUSED' OR (next_check_at IS NULL AND NOT current_observation))
);
CREATE INDEX monitors_page_idx ON monitor.monitors (created_at, id);
